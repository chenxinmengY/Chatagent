import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {startDshBridgeHost} from '../packages/dsh-bridge/host.mjs';
import {sandbox} from './helpers.mjs';

test('安装版独立启动、重复打开、拒绝外来进程、导入桥接与保留资料的正常退出',async t=>{
  if(process.platform!=='win32')return t.skip('Windows installed launcher');
  let cleanup;const {root}=sandbox({after:fn=>cleanup=fn});
  const install=path.join(root,'安装 程序'),data=path.join(root,'用户 资料'),foreign=path.join(root,'另一份资料');
  for(const folder of ['runtime','app/apps/desktop'])fs.mkdirSync(path.join(install,folder),{recursive:true});
  fs.copyFileSync(process.execPath,path.join(install,'runtime/node.exe'));
  for(const folder of ['packages','apps/service','apps/web'])fs.cpSync(path.resolve(folder),path.join(install,'app',folder),{recursive:true});
  fs.copyFileSync('package.json',path.join(install,'app/package.json'));
  fs.copyFileSync('apps/desktop/installed-server.mjs',path.join(install,'app/apps/desktop/installed-server.mjs'));
  fs.copyFileSync('apps/desktop/installed-bootstrap.ps1',path.join(install,'installed-bootstrap.ps1'));
  const exec=promisify(execFile),launch=(args=[],userRoot=data)=>exec('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(install,'installed-bootstrap.ps1'),...args],{encoding:'utf8',windowsHide:true,timeout:20000,env:{...process.env,CHATAGENT_INSTALL_DATA:userRoot}});
  let host;
  t.after(async()=>{try{await launch(['-Stop']);await host?.close();}finally{cleanup();}});
  const first=JSON.parse((await launch()).stdout);
  assert.equal(first.firstRun,true);assert.equal(first.dataRoot,data);assert.ok(first.setupPrompt.includes(install));
  const lock=()=>JSON.parse(fs.readFileSync(path.join(data,'chat/service.lock'),'utf8'));
  const pid=lock().pid;
  assert.equal(JSON.parse((await launch()).stdout).url,first.url);assert.equal(lock().pid,pid);
  assert.match(await(await fetch(first.url+'/installed-start')).text(),/导入 DSH 连接配置/);
  fs.mkdirSync(foreign);fs.writeFileSync(path.join(foreign,'installed-settings.json'),JSON.stringify({dataRoot:foreign,port:new URL(first.url).port*1}));
  await assert.rejects(launch(['-Stop'],foreign));assert.equal(lock().pid,pid);
  assert.equal((await fetch(first.url+'/v1/bootstrap')).status,200);
  const token='synthetic-installed-bridge-token-'.repeat(3),tokenFile=path.join(root,'token.txt'),connection=path.join(root,'bridge-client.json');
  fs.writeFileSync(tokenFile,token);
  fs.writeFileSync(connection,JSON.stringify({bridgeUrl:'https://127.0.0.1:37827',tokenFile}));
  await assert.rejects(launch(['-Connection',connection]));assert.equal(lock().pid,pid);
  let prompts=0;
  host=await startDshBridgeHost({root:path.join(root,'bridge'),token,port:0,driver:{configure(){},async ensure(){},status:()=>({connected:true,tools:[],plugins:[]}),async prompt(){prompts++;},events:()=>[],async flush(){}}});
  fs.writeFileSync(connection,JSON.stringify({bridgeUrl:host.url,tokenFile,dataRoot:foreign,port:37821}));
  const connected=JSON.parse((await launch(['-Connection',connection])).stdout);
  assert.equal(connected.firstRun,false);assert.equal(connected.url,first.url);
  assert.equal((await(await fetch(first.url+'/v1/bootstrap')).json()).backend,'dsh-bridge');
  assert.equal(prompts,0);assert.notEqual(lock().pid,pid);
  const saved=fs.readFileSync(path.join(data,'connection.json'));
  await assert.rejects(launch(['-Connection',connection]));assert.deepEqual(fs.readFileSync(path.join(data,'connection.json')),saved);
  await launch(['-Stop']);assert.ok(!fs.existsSync(path.join(data,'chat/service.lock')));assert.ok(fs.statSync(path.join(data,'chat/chat.sqlite')).size>4096);
  assert.ok(fs.existsSync(path.join(data,'connection.json')));assert.equal(prompts,0);
});
